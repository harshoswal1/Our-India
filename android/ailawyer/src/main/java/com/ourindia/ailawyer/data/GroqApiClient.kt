package com.ourindia.ailawyer.data

import com.ourindia.ailawyer.BuildConfig
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.encodeToString
import kotlinx.serialization.json.Json
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import java.util.concurrent.TimeUnit

@Serializable
data class ChatMessage(
    val role: String, // "system", "user", "assistant"
    val content: String,
    val timestamp: Long = System.currentTimeMillis()
)

@Serializable
private class GroqChatRequest(
    val model: String = "openai/gpt-oss-120b",
    val messages: List<GroqMessage>,
    val temperature: Double = 0.3,
    @SerialName("max_tokens") val maxTokens: Int = 2048
)

@Serializable
private class GroqMessage(
    val role: String,
    val content: String
)

@Serializable
private class GroqChatResponse(
    val choices: List<GroqChoice> = emptyList()
)

@Serializable
private class GroqChoice(
    val message: GroqMessage
)

object GroqApiClient {
    private const val GROQ_URL = "https://api.groq.com/openai/v1/chat/completions"
    private const val USER_AGENT = "Mozilla/5.0 (Android; Mobile; OurIndia-AILawyer/1.0)"
    private val json = Json { ignoreUnknownKeys = true; isLenient = true; encodeDefaults = true }

    private val client = OkHttpClient.Builder()
        .connectTimeout(30, TimeUnit.SECONDS)
        .readTimeout(60, TimeUnit.SECONDS)
        .writeTimeout(30, TimeUnit.SECONDS)
        .build()

    const val SYSTEM_LEGAL_PROMPT = """
You are "AI Lawyer India" (न्याय साथी), an expert Indian Legal Advisor & Advocate AI.
Your purpose is to provide clear, actionable, and accurate legal guidance to Indian citizens, advocates, and students under Indian Jurisprudence.

Key Directives:
1. Reference the new criminal codes enacted in 2024:
   - Bharatiya Nyaya Sanhita (BNS) 2023 (cite both new BNS and corresponding legacy IPC section for clarity).
   - Bharatiya Nagarik Suraksha Sanhita (BNSS) 2023 (cite CrPC equivalents).
   - Bharatiya Sakshya Adhiniyam (BSA) 2023 (cite Indian Evidence Act equivalents).
2. Reference relevant Indian statutes where applicable: Constitution of India, Consumer Protection Act 2019, Negotiable Instruments Act (Sec 138), Motor Vehicles Act, RTI Act 2005, Domestic Violence Act 2005, IT Act 2000.
3. For dispute queries: Explain (a) Legal Rights, (b) Applicable Sections & Punishments, (c) Step-by-Step Procedure to take action, (d) Available Forums/Courts, (e) Limitation Period.
4. Maintain a professional, empathetic, and authoritative legal tone.
5. Clarify that while this guidance is based on Indian Law, it is for legal awareness and should be verified with a practicing advocate for litigation.
"""

    suspend fun sendQuery(
        userQuery: String,
        conversationHistory: List<ChatMessage> = emptyList(),
        customSystemPrompt: String = SYSTEM_LEGAL_PROMPT
    ): Result<String> = withContext(Dispatchers.IO) {
        try {
            val messages = mutableListOf<GroqMessage>()
            messages.add(GroqMessage(role = "system", content = customSystemPrompt))

            // Add previous recent context (up to last 6 messages)
            conversationHistory.takeLast(6).forEach { msg ->
                messages.add(GroqMessage(role = msg.role, content = msg.content))
            }
            messages.add(GroqMessage(role = "user", content = userQuery))

            val reqBody = json.encodeToString(
                GroqChatRequest(
                    model = "openai/gpt-oss-120b",
                    messages = messages
                )
            )

            val request = Request.Builder()
                .url(GROQ_URL)
                .addHeader("Authorization", "Bearer ${BuildConfig.GROQ_API_KEY}")
                .addHeader("Content-Type", "application/json")
                .addHeader("User-Agent", USER_AGENT)
                .post(reqBody.toRequestBody("application/json".toMediaType()))
                .build()

            client.newCall(request).execute().use { response ->
                val body = response.body?.string().orEmpty()
                if (!response.isSuccessful) {
                    // Try fallback fast model
                    return@withContext fallbackToFastModel(messages, body)
                }

                val parsed = json.decodeFromString<GroqChatResponse>(body)
                val reply = parsed.choices.firstOrNull()?.message?.content
                    ?: "No response generated by legal AI engine."
                Result.success(reply)
            }
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    private suspend fun fallbackToFastModel(messages: List<GroqMessage>, previousError: String): Result<String> = withContext(Dispatchers.IO) {
        try {
            val reqBody = json.encodeToString(
                GroqChatRequest(
                    model = "openai/gpt-oss-20b",
                    messages = messages
                )
            )

            val request = Request.Builder()
                .url(GROQ_URL)
                .addHeader("Authorization", "Bearer ${BuildConfig.GROQ_API_KEY}")
                .addHeader("Content-Type", "application/json")
                .addHeader("User-Agent", USER_AGENT)
                .post(reqBody.toRequestBody("application/json".toMediaType()))
                .build()

            client.newCall(request).execute().use { response ->
                val body = response.body?.string().orEmpty()
                if (!response.isSuccessful) {
                    return@withContext Result.failure(Exception("Cloud Legal API error: ${response.code} ($body)"))
                }
                val parsed = json.decodeFromString<GroqChatResponse>(body)
                val reply = parsed.choices.firstOrNull()?.message?.content
                    ?: "No response generated."
                Result.success(reply)
            }
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}
